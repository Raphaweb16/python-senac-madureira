/*     Monte um programa que receba um valor e verificar se esse valor é um número par ou ímpar */
let valor = Number(prompt("Informe o valor"));
if (valor % 2 == 0) {
    console.log("Número Par");
    alert("Número par");
    document.write("Número par");
}  else {
    console.log("Número impar");
    alert("Número impar");
    document.write("Número impar");
} 
